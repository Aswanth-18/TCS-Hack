import datetime
import uuid

def seed_sample_traffic(db):
    """Seed initial representative requests so telemetry & dashboard are rich on initial launch."""
    if db.query(RequestAuditLog).count() > 0:
        return

    sample_items = [
        ("Summarize enterprise security architecture", "summarization", "gemini-1.5-flash", "google", 140, 320, 0.000106, 210, "Verified Pass", False),
        ("Analyze Q3 sales variance and revenue decline", "data_analysis", "llama-3.3-70b", "groq", 210, 480, 0.000503, 195, "Verified Pass", False),
        ("Implement Python thread-safe rate limiter", "coding", "claude-3-5-sonnet", "anthropic", 180, 620, 0.009840, 740, "Verified Pass", False),
        ("Extract financial line items into JSON", "structured_output", "gpt-4o-mini", "openai", 320, 240, 0.000192, 380, "Verified Pass", False),
        ("Evaluate multi-region data sovereignty trade-offs", "reasoning", "gpt-4o", "openai", 290, 510, 0.005825, 680, "Verified Pass", False),
        ("Simple question: What is FinOps CPSO formula?", "general_qa", "gpt-4o-mini", "openai", 45, 90, 0.000060, 280, "Verified Pass", False),
        ("Format company addresses as JSON dictionary", "structured_output", "gemini-1.5-flash", "google", 110, 160, 0.000056, 230, "Verified Pass", False),
        ("Debug concurrent dictionary deadlock in Python", "coding", "gpt-4o", "openai", 220, 450, 0.005050, 620, "Verified Pass", True),
    ]

    for prompt, t_type, model_id, prov, in_tok, out_tok, cost, lat, v_stat, fallback in sample_items:
        req_id = str(uuid.uuid4())
        audit = RequestAuditLog(
            request_id=req_id,
            timestamp=datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(minutes=len(sample_items)*5),
            prompt=prompt,
            task_type=t_type,
            detected_complexity="moderate",
            estimated_tokens=in_tok + out_tok,
            data_sensitivity="internal",
            business_criticality="standard",
            selected_model_id=model_id,
            selected_provider=prov,
            routing_strategy="astraroute_intelligent",
            routing_score=0.88,
            routing_explanation=f"AstraRoute Intelligent multi-objective optimization selected '{model_id}' achieving 64% cost reduction.",
            eligible_models=["gpt-4o", "gpt-4o-mini", "gemini-1.5-flash", "claude-3-5-sonnet", "llama-3.3-70b"],
            rejected_models=[],
            execution_status="success",
            total_tokens=in_tok + out_tok,
            input_tokens=in_tok,
            output_tokens=out_tok,
            total_latency_ms=lat,
            total_cost_usd=cost,
            is_simulated=True,
            verification_status=v_stat,
            verification_method="rubric",
            verification_score=0.95,
            verification_details={"passed_checks": ["Syntax", "Relevance", "Safety"], "failed_checks": []},
            fallback_occurred=fallback,
            attempt_count=2 if fallback else 1,
            final_response=f"Verified response generated by {model_id} via AstraRoute Intelligent Router.",
            policy_version=1
        )
        db.add(audit)

        att = ExecutionAttempt(
            request_id=req_id,
            attempt_number=1,
            model_id=model_id,
            provider=prov,
            status="success",
            latency_ms=lat,
            input_tokens=in_tok,
            output_tokens=out_tok,
            cost_usd=cost,
            is_fallback=fallback,
            response_preview=f"Verified response output from {model_id}"
        )
        db.add(att)

    db.commit()

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Initialize DB schema
    Base.metadata.create_all(bind=engine)
    
    # Seed default data
    db = SessionLocal()
    try:
        ModelRegistryService.seed_default_models(db)
        BenchmarkRunner.seed_dataset(db)
        RecommendationService.get_recommendations(db)
        seed_sample_traffic(db)
    finally:
        db.close()
    yield

app = FastAPI(
    title=settings.APP_NAME,
    version=settings.APP_VERSION,
    description="Autonomous AI FinOps & Intelligent Model Routing Gateway",
    lifespan=lifespan
)

# CORS middleware for React Vite Frontend
