import asyncio
import time
import random
import json
from app.services.provider_adapters.base import BaseProviderAdapter, AdapterExecutionResult

class SimulatorAdapter(BaseProviderAdapter):
    """
    High-Fidelity AI Provider Simulator.
    Simulates real model responses, realistic latency, and token consumption
    when real provider credentials are not present.
    Clearly marks is_simulated=True in telemetry.
    """

    def __init__(self, provider_name: str = "simulator"):
        self.provider_name = provider_name

    async def execute(
        self,
        prompt: str,
        model_id: str,
        max_tokens: int = 1500,
        temperature: float = 0.2,
        simulate_failure: bool = False
    ) -> AdapterExecutionResult:
        start_time = time.perf_counter()

        # Simulated latency: 150ms to 450ms based on model tier
        base_latency = 0.15 if "mini" in model_id or "flash" in model_id or "haiku" in model_id else 0.35
        simulated_sleep = base_latency + (random.random() * 0.1)
        await asyncio.sleep(simulated_sleep)

        # Trigger failure if specifically requested (for fallback & recovery demonstrations)
        if simulate_failure:
            elapsed_ms = int((time.perf_counter() - start_time) * 1000)
            return AdapterExecutionResult(
                model_id=model_id,
                provider=self.provider_name,
                response_text="",
                input_tokens=max(10, len(prompt.split()) * 2),
                output_tokens=0,
                total_tokens=max(10, len(prompt.split()) * 2),
                latency_ms=elapsed_ms,
                status="timeout",
                error_message="Gateway timeout (504): Provider response timed out after 4000ms threshold.",
                is_simulated=True,
                provider_request_id=f"sim-err-{int(time.time()*1000)}"
            )

        # Generate contextual response based on prompt keywords
        prompt_lower = prompt.lower()
        if "def " in prompt_lower or "python" in prompt_lower or "code" in prompt_lower or "function" in prompt_lower:
            response_text = (
                "```python\n"
                "# Generated by " + model_id + " (AstraRoute Autonomous Gateway)\n"
                "def solve_task(data):\n"
                "    \"\"\"\n"
                "    Optimized implementation with O(N) linear time complexity\n"
                "    and strict input validation.\n"
                "    \"\"\"\n"
                "    if not data:\n"
                "        return []\n"
                "    return [item.strip() for item in data if item]\n"
                "\n"
                "# Verification assertion\n"
                "assert solve_task(['a ', 'b', '']) == ['a', 'b']\n"
                "print('Execution verified successfully.')\n"
                "```"
            )
        elif "sales" in prompt_lower or "revenue" in prompt_lower or "decrease" in prompt_lower or "report" in prompt_lower:
            response_text = (
                "### Executive Financial Summary & Root-Cause Analysis\n\n"
                "**1. Core Findings:**\n"
                "- **Gross Revenue Variance:** -14.2% quarter-over-quarter, driven predominantly by enterprise churn in APAC.\n"
                "- **Customer Acquisition Cost (CAC):** Rose 22% due to increased paid channel saturation.\n"
                "- **Net Retention Rate (NRR):** Contracted to 94% from 106% in previous quarters.\n\n"
                "**2. Remediation Strategy:**\n"
                "1. Focus account management on Tier-1 enterprise renewals with customized SLAs.\n"
                "2. Rationalize outbound marketing budget to higher-converting product-led organic channels.\n"
                "3. Introduce tiered consumption pricing to lower upfront customer friction."
            )
        elif "json" in prompt_lower or "schema" in prompt_lower or "structured" in prompt_lower:
            response_text = json.dumps({
                "status": "success",
                "extracted_entities": [
                    {"category": "metric", "name": "revenue_growth", "value": -0.142},
                    {"category": "region", "name": "APAC", "impact": "negative"}
                ],
                "confidence_score": 0.94,
                "model_routed": model_id,
                "timestamp_iso": "2026-10-31T05:00:00Z"
            }, indent=2)
        elif "summarize" in prompt_lower or "summary" in prompt_lower or "tldr" in prompt_lower:
            response_text = (
                "**Key Takeaways:**\n"
                "1. Autonomous model routing lowers enterprise inferencing expenditures by up to 68%.\n"
                "2. Deterministic policy filtering prevents sensitive data leakage to unapproved providers.\n"
                "3. Task-specific verification guarantees answer correctness through automated checks and fallback recovery."
            )
        else:
            response_text = (
                f"AstraRoute AI processed this query using {model_id}.\n\n"
                "The analysis satisfies all configured constraints: quality target, budget limitations, "
                "and latency ceilings. Telemetry and cost tracking have been recorded in the central FinOps ledger."
            )

        elapsed_ms = int((time.perf_counter() - start_time) * 1000)
        input_toks = max(15, len(prompt.split()) * 2)
        output_toks = max(40, len(response_text.split()) * 2)

        return AdapterExecutionResult(
            model_id=model_id,
            provider=self.provider_name,
            response_text=response_text,
            input_tokens=input_toks,
            output_tokens=output_toks,
            total_tokens=input_toks + output_toks,
            latency_ms=elapsed_ms,
            status="success",
            is_simulated=True,
            provider_request_id=f"sim-req-{int(time.time()*1000)}",
            raw_metadata={"temperature": temperature, "simulated": True}
        )

